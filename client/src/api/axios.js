import axios from 'axios';

const api = axios.create({
  baseURL: import.meta.env.VITE_API_URL || '/api',
  headers: {
    'Content-Type': 'application/json',
  },
});

// Request interceptor to attach JWT token
api.interceptors.request.use(
  (config) => {
    const token = localStorage.getItem('hotelpro_token');
    if (token) {
      config.headers.Authorization = `Bearer ${token}`;
    }
    return config;
  },
  (error) => Promise.reject(error)
);

// Response interceptor to catch unauthorized tokens
api.interceptors.response.use(
  (response) => response,
  (error) => {
    if (error.response && error.response.status === 401) {
      const currentToken = localStorage.getItem('hotelpro_token');
      if (currentToken) {
        localStorage.removeItem('hotelpro_token');
        localStorage.removeItem('hotelpro_user');
        window.dispatchEvent(new Event('hotelpro:unauthorized'));
      }
    }
    return Promise.reject(error);
  }
);

export default api;
